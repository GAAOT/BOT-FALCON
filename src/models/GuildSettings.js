const mongoose = require('mongoose');
const schema = new mongoose.Schema({
  guildId: { type: String, required: true, unique: true },
  language: { type: String, enum: ['ar', 'en'], default: null },
  welcomeChannelId: String,
  leaveChannelId: String,
  logsChannelId: String,
  ticketCategoryId: String,
  ticketSupportRoleId: String,
  ticketPanelChannelId: String,
  ticketPanelMessageId: String,
  staffRoleId: String,
  seniorStaffRoleId: String,
  gamesChannelId: String,
  verificationChannelId: String,
  verificationRoleId: String,
  autoRoleId: String,
  antiSpamEnabled: { type: Boolean, default: true },
  antiSpamMax: { type: Number, default: 2 },
  antiSpamWindowMs: { type: Number, default: 3000 },
  antiLinkEnabled: { type: Boolean, default: false },
  antiInviteEnabled: { type: Boolean, default: true },
  badWords: { type: [String], default: [] },
  premiumUntil: { type: Date, default: null },
  premiumBy: String,
  economyDaily: { type: Map, of: Date, default: {} },
  economyWork: { type: Map, of: Date, default: {} },
}, { timestamps: true });
module.exports = mongoose.model('GuildSettings', schema);
